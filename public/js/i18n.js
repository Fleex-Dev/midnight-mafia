function dynamicEnglish(text) {
  let match;
  if ((match = text.match(/^(마피아|경찰|의사|시민) (\d+)$/)))
    return `${EN[match[1]]} ${match[2]}`;
  if ((match = text.match(/^(\d+)\/(\d+)명$/)))
    return `${match[1]}/${match[2]} players`;
  if ((match = text.match(/^(\d+)명 더 필요해요$/)))
    return `${match[1]} more ${match[1] === "1" ? "player" : "players"} needed`;
  if ((match = text.match(/^생존자 (\d+)명$/))) return `${match[1]} survivors`;
  if ((match = text.match(/^동료: (.+)$/))) return `Teammates: ${match[1]}`;
  if ((match = text.match(/^(.+) · (마피아|마피아 아님)$/)))
    return `${match[1]} · ${EN[match[2]] || match[2]}`;
  if ((match = text.match(/^(.+) 내보내기$/))) return `Remove ${match[1]}`;
  if ((match = text.match(/^(\d+)번째 밤 · (.+)$/)))
    return `Night ${match[1]} · ${EN[match[2]] || match[2]}`;
  if ((match = text.match(/^(\d+)번째 아침$/))) return `Morning ${match[1]}`;
  if ((match = text.match(/^(\d+)번째 낮$/))) return `Day ${match[1]}`;
  if ((match = text.match(/^(\d+)라운드$/))) return `Round ${match[1]}`;
  if ((match = text.match(/^(마피아|경찰|의사|시민) · 감추기$/)))
    return `${EN[match[1]]} · Hide`;
  if ((match = text.match(/^(\d+)표를 받아 과반수를 넘었습니다\.$/)))
    return `${match[1]} votes reached the majority.`;
  if (
    (match = text.match(/^최다 득표 (\d+)표 · 추방 기준 (\d+)표$/))
  )
    return `Top vote: ${match[1]} · ${match[2]} needed to exile`;
  if ((match = text.match(/^(\d+)\/(\d+)명이 선택을 마쳤습니다\.$/)))
    return `${match[1]} of ${match[2]} players have chosen.`;
  if ((match = text.match(/^(\d+)\/(\d+)명이 결과를 확인했습니다\.$/)))
    return `${match[1]} of ${match[2]} players have reviewed the result.`;
  if ((match = text.match(/^(\d+)\/(\d+)명이 투표할 준비를 마쳤습니다\.$/)))
    return `${match[1]} of ${match[2]} players are ready to vote.`;
  if ((match = text.match(/^(\d+)\/(\d+)명이 밤을 시작할 준비를 마쳤습니다\.$/)))
    return `${match[1]} of ${match[2]} players are ready for night.`;
  if (
    (match = text.match(
      /^(\d+)번째 밤입니다\. 각자의 화면에서 행동을 선택하세요\.$/,
    ))
  )
    return `Night ${match[1]}. Choose your action on your own screen.`;
  if (
    (match = text.match(
      /^(.+) 님이 밤사이 희생되었습니다\. 정체는 (마피아|경찰|의사|시민)(?:이)?었습니다\.$/,
    ))
  )
    return `${match[1]} was the night's victim. Their role was ${EN[match[2]] || match[2]}.`;
  if (
    (match = text.match(
      /^(.+) 님이 투표로 지목됐습니다\. 정체는 (.+)였습니다\.$/,
    ))
  )
    return `${match[1]} was exiled by vote. Their role was ${EN[match[2]] || match[2]}.`;
  if (
    (match = text.match(
      /^(.+) 님이 투표로 추방되었습니다\. 정체는 (마피아|경찰|의사|시민)(?:이)?었습니다\.$/,
    ))
  )
    return `${match[1]} was exiled by vote. Their role was ${EN[match[2]] || match[2]}.`;
  if (
    (match = text.match(
      /^(.+) 님이 투표로 마피아임이 밝혀졌습니다\.$/,
    ))
  )
    return `${match[1]} was identified as Mafia by vote.`;
  if (
    (match = text.match(
      /^(.+) 님은 (마피아|경찰|의사|시민)(?:이)?었습니다\.$/,
    ))
  )
    return `${match[1]} was ${EN[match[2]] || match[2]}.`;
  if (
    (match = text.match(
      /^(.+) 님이 밤사이 희생되었습니다\. 정체는 (마피아|경찰|의사|시민)(?:이)?었습니다\. (모든 마피아를 찾아냈습니다\. 시민 팀 승리!|마피아가 마을을 장악했습니다\. 마피아 팀 승리!)$/,
    ))
  )
    return `${match[1]} was the night's victim. Their role was ${EN[match[2]] || match[2]}. ${EN[match[3]] || match[3]}`;
  return text;
}

export function tr(text) {
  if (locale !== "en") return text;
  return EN[text] || dynamicEnglish(text);
}

export function localize(root) {
  if (locale !== "en") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (node.parentElement?.closest("[translate='no']")) continue;
    const original = node.nodeValue;
    const trimmed = original.trim();
    if (!trimmed) continue;
    const translated = tr(trimmed);
    if (translated !== trimmed)
      node.nodeValue = original.replace(trimmed, translated);
  }
  for (const element of root.querySelectorAll(
    "[placeholder], [aria-label], [title]",
  )) {
    for (const attribute of ["placeholder", "aria-label", "title"]) {
      if (element.hasAttribute(attribute))
        element.setAttribute(attribute, tr(element.getAttribute(attribute)));
    }
  }
}

export function setLocalePreference(preference) {
  const next = ["auto", "ko", "en"].includes(preference) ? preference : "auto";
  try {
    localStorage.setItem("midnight-mafia-locale-preference", next);
  } catch {}
  const url = new URL(location.href);
  if (next === "auto") url.searchParams.delete("lang");
  else url.searchParams.set("lang", next);
  location.href = url.toString();
}
